// MARK: - TestKeys

/// Installs a real X25519 key pair into the Keychain so the encryption paths can be exercised for
/// what they actually are.
///
/// The crypto is deliberately *not* mocked. The `crypto_box_seal` / secretstream round trip is the
/// part of this app most expensive to get subtly wrong, and a fake that always "decrypts" would
/// assert nothing about it. libsodium's `crypto_box` uses X25519 keys, which is exactly what
/// `Curve25519.KeyAgreement` produces, so a CryptoKit-generated pair is interchangeable with the
/// one the web app exports.
enum TestKeys {

    /// Generates a pair and stores it under the same Keychain keys the app reads.
    @discardableResult
    static func install() -> KeyBundle {
        let priv = Curve25519.KeyAgreement.PrivateKey()
        let bundle = KeyBundle(
            publicKey: base64URL(priv.publicKey.rawRepresentation),
            privateKey: base64URL(priv.rawRepresentation),
            keyVersion: "1"
        )
        KeyImportService.storeKeys(bundle)
        return bundle
    }

    static func remove() {
        KeyImportService.removeKeys()
    }

    /// A valid key-file payload, in the format the web app exports.
    static func keyFileJSON() -> Data {
        let priv = Curve25519.KeyAgreement.PrivateKey()
        let dict = [
            "public_key": base64URL(priv.publicKey.rawRepresentation),
            "private_key": base64URL(priv.rawRepresentation),
            "key_version": "1",
        ]
        return try! JSONSerialization.data(withJSONObject: dict)
    }

    static func base64URL(_ data: Data) -> String {
        data.base64EncodedString()
            .replacingOccurrences(of: "+", with: "-")
            .replacingOccurrences(of: "/", with: "_")
            .replacingOccurrences(of: "=", with: "")
    }
}

// MARK: - WebVault

/// A key vault produced by the *web* implementation, captured verbatim.
///
/// Generated by running `e2e-crypto`'s own `hash-wasm` and `libsodium-wrappers` over fixed inputs —
/// see `web/packages/e2e-crypto/src/{kdf,vault}.ts` — rather than by this app encrypting something
/// and decrypting it again. That distinction is the entire point: a self-consistent round trip
/// passes just as happily when both halves are wrong together, and the failure mode this guards
/// against is an account that unlocks on the web and not on the phone.
///
/// Regenerate by re-running that script; do not "fix" a failure by editing these constants.
enum WebVault {

    static let password = "correct horse battery staple"

    /// Argon2id: salt `00 01 02 … 0f`, t=3, m=64 MiB, p=1 — the web client's defaults.
    static let argon2ParamsJSON =
        #"{"kdf":"argon2id","salt":"AAECAwQFBgcICQoLDA0ODw","iterations":3,"memoryKiB":65536,"parallelism":1}"#

    /// The KEK those parameters derive from `password`, as hash-wasm computed it.
    static let kekHex = "0d1a3c6523c8f06e4e0af9c515aa5b5448cfebd6838f2d52c3d8b6ef8ddc3c2e"

    static let encryptedMasterKey =
        "bclXsqrnSw0snwX5sVb1UBXdS7kTMHLCtXRrTVPOWBd91Y9ONMla_FY6FLCCHkL0fp65T9B82BpqNgW0LpWZfvB2X7Ny2_w6"

    /// The recovery code, and the *same* master key wrapped under it — which is the property that
    /// matters: every unlock method wraps one master key, so any of them lands on one identity.
    /// Written already normalized, because that is what the client derives from.
    static let recoveryCode = "abcd-efgh"
    static let recoveryEncryptedMasterKey =
        "vsNynVj8z6DGul3Q4jOhsY0rj2SDHuWJtLN06f_yZ5mIw5zMyV79B8RxRgUePPM1A1Y7skV-6jNGt8VcTbFlPAUkUYyuboV5"

    static let encryptedIdentity =
        "qMopQyPKi8lMRyjw044yp--fZpZ7Uyyo5bzxm-CmOZiOvfTSUKlX_Ug_K-QR4LwA_PSRK0qkdnStAp7E9DG-cx9Vm8oWk0rJ"

    static let publicKey  = "rKT4EL17d-ACJum-eHGYLJOe5uEJu_oLDDjQQLy2tBY"
    static let privateKey = "3mBfEeWEWhVLQVr7Bx3XOIZHVhjZCfzYV5zcw2ayXN0"

    /// The vault as `GET /api/v1/auth/keyvault` serves it.
    static func responseJSON(methods: [String] = ["password"], version: Int = 1) -> Data {
        let unlocks = methods.enumerated().map { index, method -> String in
            let params = method == "passkey"
                ? #"{\"kdf\":\"webauthn-prf\",\"credentialId\":\"Y3JlZA\",\"prfSalt\":\"AAECAwQFBgcICQoLDA0ODw\"}"#
                : argon2ParamsJSON.replacingOccurrences(of: "\"", with: "\\\"")
            let wrapped = method == "recovery" ? recoveryEncryptedMasterKey : encryptedMasterKey
            return """
            {"id":"unlock-\(index)","method":"\(method)","label":"\(method.capitalized)",
             "encryptedMasterKey":"\(wrapped)","params":"\(params)",
             "createdAt":"2026-08-01T10:00:00+00:00","lastUsedAt":null}
            """
        }
        return Data("""
        {"encryptedIdentity":"\(encryptedIdentity)","publicKey":"\(publicKey)",
         "version":\(version),"unlocks":[\(unlocks.joined(separator: ","))]}
        """.utf8)
    }

    static var argon2Params: Argon2Params {
        try! JSONDecoder().decode(Argon2Params.self, from: Data(argon2ParamsJSON.utf8))
    }
}

// MARK: - TestTokens

/// Puts an access token in the Keychain so services believe they are signed in.
enum TestTokens {

    /// Decodes to `{"alg":"none","typ":"JWT"}.{"sub":"test-user-id"}.` — a real (if unsigned) JWT
    /// shape rather than an opaque string, because `AccessToken.currentUserID()` reads the `sub`
    /// claim out of it.
    static let userId = "test-user-id"
    static let defaultAccessToken =
        "eyJhbGciOiJub25lIiwidHlwIjoiSldUIn0.eyJzdWIiOiJ0ZXN0LXVzZXItaWQifQ."

    static func install(accessToken: String = TestTokens.defaultAccessToken) {
        KeychainService.save(accessToken, forKey: AuthService.accessTokenKey)
        // Far-future expiry so `refreshTokenIfNeeded` short-circuits and no test accidentally
        // depends on a refresh round trip it did not stub.
        let expiry = ISO8601DateFormatter().string(from: Date().addingTimeInterval(3600))
        KeychainService.save(expiry, forKey: AuthService.tokenExpiryKey)
    }

    static func remove() {
        KeychainService.delete(forKey: AuthService.accessTokenKey)
        KeychainService.delete(forKey: AuthService.refreshTokenKey)
        KeychainService.delete(forKey: AuthService.tokenExpiryKey)
    }
}

