// MARK: - Fixtures

enum Fixture {

    /// A library item with sensible defaults, so a test only states what it cares about.
    static func item(id: String = "photo-1",
                     fileID: String = "file-1",
                     fileName: String = "IMG_0001.jpg",
                     mimeType: String = "image/jpeg",
                     sizeBytes: Int64 = 2_400_000,
                     thumbnailBase64: String? = nil,
                     isStarred: Bool = false,
                     isArchived: Bool = false,
                     captureDate: Date? = Date(timeIntervalSince1970: 1_700_000_000),
                     createdAt: Date = Date(timeIntervalSince1970: 1_700_100_000),
                     metadata: MediaMetadata? = nil) -> MediaItem {
        MediaItem(id: id, fileID: fileID, fileName: fileName, mimeType: mimeType,
                  sizeBytes: sizeBytes, thumbnailBase64: thumbnailBase64,
                  thumbnailMIMEType: thumbnailBase64 == nil ? nil : "image/jpeg",
                  isStarred: isStarred, isArchived: isArchived, captureDate: captureDate,
                  createdAt: createdAt, updatedAt: createdAt, metadata: metadata)
    }

    /// The RFC 3339 shape the Photos endpoints emit (`chrono`'s `to_rfc3339()`).
    static func rfc3339(_ date: Date) -> String {
        let formatter = DateFormatter()
        formatter.dateFormat = "yyyy-MM-dd'T'HH:mm:ss.SSSSSSSSSXXXXX"
        formatter.locale = Locale(identifier: "en_US_POSIX")
        formatter.timeZone = TimeZone(secondsFromGMT: 0)
        return formatter.string(from: date)
    }

    /// One `PhotoResponse`, as the server serializes it.
    static func photoJSON(id: String = "photo-1",
                          fileID: String = "file-1",
                          fileName: String = "IMG_0001.jpg",
                          mimeType: String = "image/jpeg",
                          sizeBytes: Int = 2_400_000,
                          thumbnail: String? = nil,
                          isStarred: Bool = false,
                          isArchived: Bool = false,
                          captureDate: Date? = Date(timeIntervalSince1970: 1_700_000_000),
                          createdAt: Date = Date(timeIntervalSince1970: 1_700_100_000)) -> String {
        let thumbnailField = thumbnail.map { "\"\($0)\"" } ?? "null"
        let thumbnailMIME = thumbnail == nil ? "null" : "\"image/jpeg\""
        let capture = captureDate.map { "\"\(rfc3339($0))\"" } ?? "null"
        return """
        {"id":"\(id)","fileId":"\(fileID)","fileName":"\(fileName)","mimeType":"\(mimeType)",
         "sizeBytes":\(sizeBytes),"contentUrl":"/api/v1/drive/files/\(fileID)",
         "thumbnail":\(thumbnailField),"thumbnailMimeType":\(thumbnailMIME),
         "isStarred":\(isStarred),"isArchived":\(isArchived),"captureDate":\(capture),
         "createdAt":"\(rfc3339(createdAt))","updatedAt":"\(rfc3339(createdAt))","metadata":null}
        """
    }

    static func listingJSON(_ photos: [String]) -> Data {
        Data("""
        {"photos":[\(photos.joined(separator: ","))],"total":\(photos.count)}
        """.utf8)
    }

    /// One `AlbumResponse`.
    static func albumJSON(id: String = "album-1",
                          title: String = "Trip",
                          isAuto: Bool = false,
                          photoCount: Int = 0,
                          createdAt: Date = Date(timeIntervalSince1970: 1_700_100_000)) -> String {
        """
        {"id":"\(id)","title":"\(title)","description":null,"isAuto":\(isAuto),"personId":null,
         "photoCount":\(photoCount),"createdAt":"\(rfc3339(createdAt))",
         "updatedAt":"\(rfc3339(createdAt))"}
        """
    }
}

// MARK: - TestImages

/// Real image data, because everything the rendition ladder does is ImageIO reading actual pixels.
/// A `Data("not a jpeg")` would exercise the error path and nothing else.
enum TestImages {

    /// A JPEG with two flat regions, so a downscale still has something to encode.
    ///
    /// Rendered at scale 1 so `size` is pixels rather than points — otherwise the same test asserts
    /// against a 2× image on one simulator and a 3× image on another.
    static func jpeg(size: CGFloat = 64, quality: CGFloat = 0.9) -> Data {
        let format = UIGraphicsImageRendererFormat()
        format.scale = 1
        let renderer = UIGraphicsImageRenderer(size: CGSize(width: size, height: size),
                                               format: format)
        let image = renderer.image { context in
            UIColor.systemTeal.setFill()
            context.fill(CGRect(x: 0, y: 0, width: size, height: size))
            UIColor.black.setFill()
            context.fill(CGRect(x: 0, y: 0, width: size / 2, height: size / 2))
        }
        return image.jpegData(compressionQuality: quality) ?? Data()
    }

    /// The same picture with real EXIF, TIFF, and GPS blocks written into it.
    ///
    /// Written through `CGImageDestination` rather than hand-assembled, so what the extractor reads
    /// back is a genuine JPEG APP1 segment laid out by the same framework a camera's file would be
    /// parsed with. A fixture that faked the dictionary would assert that ImageIO can round-trip a
    /// dictionary, which is not the thing under test.
    ///
    /// - Parameters:
    ///   - latitude: the *magnitude*, as EXIF stores it. The hemisphere is `latitudeRef`, which is
    ///     the half a naive reader drops — see `MediaMetadataExtractor.coordinate(from:)`.
    static func jpegWithMetadata(size: CGFloat = 64,
                                 make: String? = "Apple",
                                 model: String? = "iPhone 15 Pro",
                                 lens: String? = "iPhone 15 Pro back triple camera 6.765mm f/1.78",
                                 exposureTime: Double? = 1.0 / 120,
                                 fNumber: Double? = 1.78,
                                 iso: Int? = 200,
                                 focalLength: Double? = 6.765,
                                 dateTimeOriginal: String? = "2024:06:15 14:25:36",
                                 latitude: Double? = nil, latitudeRef: String = "N",
                                 longitude: Double? = nil, longitudeRef: String = "E") -> Data {
        guard let source = CGImageSourceCreateWithData(jpeg(size: size) as CFData, nil),
              let image = CGImageSourceCreateImageAtIndex(source, 0, nil) else { return Data() }

        var exif: [CFString: Any] = [:]
        if let exposureTime { exif[kCGImagePropertyExifExposureTime] = exposureTime }
        if let fNumber { exif[kCGImagePropertyExifFNumber] = fNumber }
        if let iso { exif[kCGImagePropertyExifISOSpeedRatings] = [iso] }
        if let focalLength { exif[kCGImagePropertyExifFocalLength] = focalLength }
        if let dateTimeOriginal { exif[kCGImagePropertyExifDateTimeOriginal] = dateTimeOriginal }
        if let lens { exif[kCGImagePropertyExifLensModel] = lens }

        var tiff: [CFString: Any] = [:]
        if let make { tiff[kCGImagePropertyTIFFMake] = make }
        if let model { tiff[kCGImagePropertyTIFFModel] = model }

        var gps: [CFString: Any] = [:]
        if let latitude {
            gps[kCGImagePropertyGPSLatitude] = latitude
            gps[kCGImagePropertyGPSLatitudeRef] = latitudeRef
        }
        if let longitude {
            gps[kCGImagePropertyGPSLongitude] = longitude
            gps[kCGImagePropertyGPSLongitudeRef] = longitudeRef
        }

        var properties: [CFString: Any] = [:]
        if !exif.isEmpty { properties[kCGImagePropertyExifDictionary] = exif }
        if !tiff.isEmpty { properties[kCGImagePropertyTIFFDictionary] = tiff }
        if !gps.isEmpty { properties[kCGImagePropertyGPSDictionary] = gps }

        let output = NSMutableData()
        guard let destination = CGImageDestinationCreateWithData(
            output, UTType.jpeg.identifier as CFString, 1, nil) else { return Data() }
        CGImageDestinationAddImage(destination, image, properties as CFDictionary)
        guard CGImageDestinationFinalize(destination) else { return Data() }
        return output as Data
    }
}

